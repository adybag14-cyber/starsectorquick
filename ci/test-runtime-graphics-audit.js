'use strict';
const assert=require('node:assert/strict');
const {graphicsKey,createRuntimeGraphicsAudit}=require('./runtime-graphics-audit');
assert.equal(graphicsKey('https://example.test/game/graphics/ships/a.png?v=1'),'graphics/ships/a.png');
assert.equal(graphicsKey('https://example.test/game/graphics/A%20B.PNG'),'graphics/A B.PNG');
assert.equal(graphicsKey('https://example.test/game/graphics/Ship.java'),null);
assert.equal(graphicsKey('not a URL'),null);
let audit=createRuntimeGraphicsAudit();
audit.response('https://test/graphics/ships/a.png',404);
assert.equal(audit.summary().safe,false);
audit.response('https://test/other/graphics/ships/a.png',200);
assert.equal(audit.summary().safe,true);
assert.equal(audit.summary().recoveredRequestFailures.length,1);
audit.response('https://test/State.java',404);
assert.equal(audit.summary().safe,true);
audit.console('BrowserDeferredTexture: direct-miss-load-failed key=graphics/ships/b.png error=decode');
assert.equal(audit.summary().safe,false);
assert.equal(audit.summary().directLoadFailures.length,1);
audit=createRuntimeGraphicsAudit();
audit.requestFailed('https://test/graphics/ships/a.png','net::ERR_ABORTED');
assert.equal(audit.summary().safe,true);
assert.equal(audit.summary().abortedRequests,1);
audit.requestFailed('https://test/graphics/ships/a.png','net::ERR_CONNECTION_RESET');
assert.equal(audit.summary().safe,false);
audit=createRuntimeGraphicsAudit(1);
audit.response('https://test/graphics/a.png',200);audit.response('https://test/graphics/b.png',200);
assert.equal(audit.summary().safe,false);assert.equal(audit.summary().overflow,true);
audit=createRuntimeGraphicsAudit();
audit.response('https://test/starsector-graphics-pack-v1/ships.bin',404);
audit.response('https://test/graphics/a.png',200);
assert.equal(audit.summary().safe,true);
assert.equal(audit.summary().backingPackFailures.length,1);
console.log('test-runtime-graphics-audit: OK (classification fixtures passed)');
